// Groups are probed in this order; specific before generic (egg must beat
// chicken for «تخم مرغ», potato must beat fruit for «سیب»).
const GROUP_ORDER = ['egg', 'potato', 'stew', 'yogurt', 'milk', 'cheese', 'rice', 'bread', 'pasta', 'chicken', 'meat', 'fish', 'greens', 'veg', 'fruit'];

function tight(s) {
  return String(s ?? '').replace(/\u200c/g, '').replace(/\s+/g, '').toLowerCase();
}

/** All rescue groups matching the given items — ordered, deduped. */
export function rescueGroupsFor(items) {
  const hits = [];
  for (const key of GROUP_ORDER) {
    const g = IDEAS[key];
    if (!g?.match) continue;
    const hit = (items ?? []).some((it) => g.match.test(tight(it)));
    if (hit) hits.push(g);
  }
  return hits;
}

/**
 * Build the rescue deck: idea-cards for matched leftovers + canonical base
 * terms the bank matcher can score against. Ideas are round-robined across
 * groups so a mixed rescue (برنج + مرغ) gets ideas from both.
 * Returns { ideas, bases, groups } — ideas are full card-shaped recipes.
 */
export function rescueRecipesFor(items, { household = 2, maxIdeas = 6, perGroup = 3 } = {}) {
  const groups = rescueGroupsFor(items);
  const ideas = [];
  if (groups.length === 0) {
    for (const it of IDEAS.generic.items.slice(0, maxIdeas)) ideas.push(ideaRecipe(it, household));
    return { ideas, bases: [], groups: [] };
  }
  // Round-robin across groups — each group's next idea appended per pass.
  let added = 0;
  for (let pass = 0; pass < perGroup && added < maxIdeas; pass++) {
    for (const g of groups) {
      if (added >= maxIdeas) break;
      const idea = g.items[pass];
      if (!idea) continue;
      ideas.push(ideaRecipe(idea, household));
      added++;
    }
  }
  const bases = [...new Set(groups.flatMap((g) => g.base))];
  return { ideas, bases, groups };
}

/** Idea (group.items entry) → the exact card shape lib/format.js renders. */
function ideaRecipe(idea, household) {
  return {
    name: idea.name,
    rescueId: idea.id,
    bankIdx: null,
    category: 'نجات مواد',
    timeMin: idea.timeMin,
    difficulty: idea.difficulty,
    why: `ایدهٔ نجات برای ${idea.rescueOf} — قبل از فساد، سریع و کم‌دردسر.`,
    ingredients: (idea.ingredients ?? []).map(([name, qty]) => ({ name, qty })),
    steps: idea.steps ?? [],
    chefTip: idea.chefTip ?? '',
    household,
  };
}

/** Resolve a save/open callback id («ri:rice1») → idea. */
export function rescueIdeaById(id) {
  const key = String(id ?? '').trim();
  for (const g of Object.values(IDEAS)) {
    const hit = g.items.find((it) => it.id === key);
    if (hit) return hit;
  }
  return null;
}

/** Find a rescue idea by dish name (used by «📚 دستورهای من» re-open). */
export function rescueIdeaByName(name) {
  const k = tight(name);
  if (!k) return null;
  for (const g of Object.values(IDEAS)) {
    const hit = g.items.find((it) => tight(it.name) === k);
    if (hit) return hit;
  }
  for (const g of Object.values(IDEAS)) {
    const hit = g.items.find((it) => tight(it.name).includes(k) || k.includes(tight(it.name)));
    if (hit) return hit;
  }
  return null;
}

/** True when a card-shaped recipe came from the rescue KB. */
export function isRescueRecipe(recipe) {
  return Boolean(recipe?.rescueId);
}

/** Card-shaped rescue recipe for rendering/saving from an id. */
export function rescueRecipeById(id, { household = 2 } = {}) {
  const idea = rescueIdeaById(id);
  return idea ? ideaRecipe(idea, household) : null;
}

/** Card-shaped rescue recipe by name — archive re-open path. */
export function rescueRecipeByName(name, { household = 2 } = {}) {
  const idea = rescueIdeaByName(name);
  return idea ? ideaRecipe(idea, household) : null;
}

